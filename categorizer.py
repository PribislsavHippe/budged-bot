# Шаблоны дат в начале строки или по всему тексту — если видим дату + число, скорее всего это контекст
DATE_PATTERNS = [
    re.compile(r'\b\d{1,2}[./]\d{1,2}\b'),  # 09.02, 11/02
    re.compile(r'\b\d{1,2}\s+(?:и|числа|числе|число)\b', re.IGNORECASE),  # "9 и 11 числа"
    re.compile(r'\b(?:январ|феврал|март|апрел|май|июн|июл|август|сентябр|октябр|ноябр|декабр)\b', re.IGNORECASE),
]


def looks_like_question(text: str) -> bool:
    """True, если текст похож на вопрос, контекст или просьбу совета."""
    if not text or not text.strip():
        return False
    lower = text.lower().strip()

    if any(m in lower for m in QUESTION_MARKERS):
        return True
    if "?" in text:
        return True

    # Если в тексте есть упоминание нескольких дат/чисел без триггеров транзакции
    date_matches = sum(1 for p in DATE_PATTERNS if p.search(lower))
    has_transaction_trigger = any(w in lower for w in EXPENSE_TRIGGER_WORDS + INCOME_TRIGGER_WORDS)
    if date_matches >= 1 and not has_transaction_trigger:
        return True

    return False


def _normalize_amount_text(text: str) -> str:
    """Заменяет буквенные числа на цифры: 50 тысяч -> 50000, 50к -> 50000."""
    t = text.replace("\xa0", " ").lower()
    t = re.sub(
        r"(\d+(?:[.,]\d+)?)\s*(?:тысяч(?:и|а|у)?|тыс\.?|к)(?:\s|$|[^\d])",
        lambda m: str(int(float(m.group(1).replace(",", ".")) * 1000)),
        t, flags=re.IGNORECASE,
    )
    t = re.sub(r"(\d+(?:[.,]\d+)?)\s*к\b", lambda m: str(int(float(m.group(1).replace(",", ".")) * 1000)), t)
    t = re.sub(
        r"(\d+(?:[.,]\d+)?)\s*(?:млн|миллион)(?:\s|$|[^\d])",
        lambda m: str(int(float(m.group(1).replace(",", ".")) * 1_000_000)),
        t, flags=re.IGNORECASE,
    )
    t = re.sub(
        r"(\d+(?:[.,]\d+)?)\s*млрд(?:\s|$|[^\d])",
        lambda m: str(int(float(m.group(1).replace(",", ".")) * 1_000_000_000)),
        t, flags=re.IGNORECASE,
    )
    return t


def extract_amount(text: str) -> float | None:
    """Извлекает сумму из текста."""
    text_clean = _normalize_amount_text(text).replace("\xa0", " ")
    patterns = [
        r"(\d[\d\s]{0,5}[.,]\d{1,2})",
        r"(\d[\d\s]{0,6}\d)",
        r"(\d+)",
    ]
    for pattern in patterns:
        matches = re.findall(pattern, text_clean)
        for m in matches:
            try:
                val = float(m.strip().replace(" ", "").replace(",", "."))
                if 1 <= val <= 10_000_000:
                    return val
            except Exception:
                pass
    return None


def detect_type(text: str) -> str | None:
    text_lower = text.lower()
    income_score = sum(1 for w in INCOME_TRIGGER_WORDS if w in text_lower)
    expense_score = sum(1 for w in EXPENSE_TRIGGER_WORDS if w in text_lower)

    for keywords in INCOME_RULES.values():
        for kw in keywords:
            if kw in text_lower:
                income_score += 2
                break

    for keywords in EXPENSE_RULES.values():
        for kw in keywords:
            if kw in text_lower:
                expense_score += 2
                break

    if income_score > expense_score and income_score > 0:
        return "income"
    if expense_score > 0:
        return "expense"
    if extract_amount(text) is not None:
        return "expense"
    return None


def detect_category(text: str, type_: str) -> str:
    text_lower = text.lower()
    rules = INCOME_RULES if type_ == "income" else EXPENSE_RULES
    best_cat = None
    best_score = 0
    for category, keywords in rules.items():
        score = sum(1 for kw in keywords if kw in text_lower)
        if score > best_score:
            best_score = score
            best_cat = category
    if best_cat and best_score > 0:
        return best_cat
    return "Прочее"


def parse_transaction_local(text: str) -> dict | None:
    """Пытается распознать транзакцию без AI. Возвращает dict или None."""
    if looks_like_question(text):
        return None

    amount = extract_amount(text)
    if amount is None:
        return None

    type_ = detect_type(text)
    if type_ is None:
        type_ = "expense"

    category = detect_category(text, type_)
    normalized = _normalize_amount_text(text)
    desc_clean = re.sub(r'\b\d[\d\s]{0,6}(?:[.,]\d{1,2})?\b', '', normalized).strip()
    desc_clean = re.sub(r'\s+', ' ', desc_clean).strip() or text[:80]

    return {
        "type": type_,
        "amount": amount,
        "category": category,
        "description": desc_clean[:100]
    }


def parse_salary_days(text: str) -> list[int]:
    numbers = re.findall(r'\b([1-9]|[12]\d|3[01])\b', text)
    days = list(dict.fromkeys(int(n) for n in numbers))
    return sorted(days)
