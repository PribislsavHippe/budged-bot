def extract_amount(text: str) -> float | None:
    """Извлекает сумму из текста."""
    text_clean = text.replace('\xa0', ' ')
    # Ищем числа: 500, 1500, 1 500, 1500.50, 1500,50
    patterns = [
        r'(\d[\d\s]{0,5}[.,]\d{1,2})',  # с дробной частью
        r'(\d[\d\s]{0,6}\d)',             # целое число (до 8 цифр)
        r'(\d+)',                          # просто число
    ]
    for pattern in patterns:
        matches = re.findall(pattern, text_clean)
        for m in matches:
            try:
                val = float(m.strip().replace(' ', '').replace(',', '.'))
                if 1 <= val <= 10_000_000:  # разумный диапазон
                    return val
            except Exception:
                pass
    return None


def detect_type(text: str) -> str | None:
    """Определяет тип операции: expense, income или None."""
    text_lower = text.lower()

    income_score = sum(1 for w in INCOME_TRIGGER_WORDS if w in text_lower)
    expense_score = sum(1 for w in EXPENSE_TRIGGER_WORDS if w in text_lower)

    # Проверяем ключевые слова категорий доходов
    for keywords in INCOME_RULES.values():
        for kw in keywords:
            if kw in text_lower:
                income_score += 2
                break

    if income_score > expense_score and income_score > 0:
        return "income"
    if expense_score > 0 or extract_amount(text) is not None:
        return "expense"
    return None


def detect_category(text: str, type_: str) -> str:
    """Определяет категорию по ключевым словам."""
    text_lower = text.lower()
    rules = INCOME_RULES if type_ == "income" else EXPENSE_RULES

    best_cat = None
    best_score = 0

    for category, keywords in rules.items():
        score = sum(1 for kw in keywords if kw in text_lower)
        if score > best_score:
            best_score = score
            best_cat = category

    if best_cat and best_score > 0:
        return best_cat

    return "Прочее" if type_ == "income" else "Прочее"


def parse_transaction_local(text: str) -> dict | None:
    """
    Пытается распознать транзакцию из текста без AI.
    Возвращает dict или None.
    """
    text_lower = text.lower()

    # Исключаем явные вопросы и планы
    question_markers = ["?", "стоит ли", "можно ли", "как ", "сколько стоит",
                        "что думаешь", "посоветуй", "хочу купить", "думаю купить",
                        "планирую", "подскажи", "собираюсь купить", "буду покупать",
                        "надо ли", "нужно ли", "какой бюджет", "хватит ли"]
    if any(m in text_lower for m in question_markers):
        return None

    amount = extract_amount(text)
    if amount is None:
        return None

    type_ = detect_type(text)
    if type_ is None:
        # Если есть сумма но нет явного типа — считаем расходом
        type_ = "expense"

    category = detect_category(text, type_)

    return {
        "type": type_,
        "amount": amount,
        "category": category,
        "description": text[:100]
    }


def parse_salary_days(text: str) -> list[int]:
    """
    Извлекает дни зарплаты из текста.
    Примеры: "9, 18, 23, 28" / "9 и 25" / "каждые 5 и 20 число"
    """
    numbers = re.findall(r'\b([1-9]|[12]\d|3[01])\b', text)
    days = list(dict.fromkeys(int(n) for n in numbers))  # убираем дубли, сохраняем порядок
    return sorted(days)
