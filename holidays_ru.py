"""Нерабочие праздничные дни России: в эти дни гостей больше, и людей нужно больше.

Для ресторана такой день — как пятница, суббота или воскресенье: открытие в 8, двое открывают,
в смене шесть человек. Даты взяты из производственного календаря (КонсультантПлюс), переносы
2026 и 2027 годов — из постановлений правительства. Для остальных лет известны только
праздники с постоянной датой: переносы появляются в календаре примерно за год, их нужно
вносить сюда, а до тех пор день можно отметить праздничным вручную.
"""
from datetime import date, timedelta

# (месяц, день): короткое название для шапки таблицы.
FIXED = {
    **{(1, d): 'Каникулы' for d in (1, 2, 3, 4, 5, 6, 8)},
    (1, 7): 'Рождество',
    (2, 23): '23 февраля',
    (3, 8): '8 Марта',
    (5, 1): '1 Мая',
    (5, 9): '9 Мая',
    (6, 12): 'День России',
    (11, 4): 'День единства',
}

# Выходные дни по переносу: утверждены постановлениями правительства (2026 — № 1466 от
# 24.09.2025, 2027 — № 1187 от 17.09.2026).
TRANSFERS = {
    date(2025, 12, 31): 'Выходной',
    date(2026, 1, 9): 'Выходной', date(2026, 3, 9): 'Выходной',
    date(2026, 5, 11): 'Выходной', date(2026, 12, 31): 'Выходной',
    date(2027, 2, 22): 'Выходной', date(2027, 5, 3): 'Выходной', date(2027, 5, 10): 'Выходной',
    date(2027, 6, 14): 'Выходной', date(2027, 11, 5): 'Выходной', date(2027, 12, 31): 'Выходной',
}


def between(start, end):
    """Все нерабочие праздничные дни периода: {дата: короткое название}."""
    found = {}
    day = start
    while day <= end:
        name = FIXED.get((day.month, day.day)) or TRANSFERS.get(day)
        if name:
            found[day] = name
        day += timedelta(days=1)
    return found
